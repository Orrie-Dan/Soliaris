// Builds the homepage "Where we focus" map from real geodata:
//   - src/data/westAfricaMap.ts: Natural Earth 1:50m country outlines projected into the map's
//     1920×860 frame, plus a small whole-Africa outline for the locator inset.
//   - public/images/regmap-satellite.jpg: NASA Blue Marble shaded relief + bathymetry for exactly
//     the same frame, fetched from NASA GIBS (public domain).
//
// Usage: node scripts/build-africa-map.mjs path/to/ne_50m_admin_0_countries.geojson
//   then: python scripts/bake-map-imagery.py  (writes the toned public/images/regmap.webp the page shows)
// Outlines: https://github.com/nvkelso/natural-earth-vector (public domain)
//
// The frame is an equirectangular projection with a standard parallel of 14°N, so it lines up
// pixel-for-pixel with the EPSG:4326 imagery and keeps West Africa's proportions true to
// within ~3%.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const W = 1920, H = 860;
const K = 40.2; // px per degree of latitude
const KX = K * Math.cos((14 * Math.PI) / 180); // px per degree of longitude
const LON_W = -36.93, LAT_N = 24;
const LON_E = LON_W + W / KX, LAT_S = LAT_N - H / K;
const VIEW = { w: W, h: H, k: K, kx: +KX.toFixed(5), lonW: LON_W, latN: LAT_N };

const project = ([lon, lat]) => [(lon - LON_W) * VIEW.kx, (LAT_N - lat) * K];

// Locator inset: whole continent, orthographic, in a 120×130 box.
const LOC = { w: 120, h: 130, lon0: 17, lat0: 2, r: 70 };
const rad = Math.PI / 180;
function projectLoc([lon, lat]) {
  const l = (lon - LOC.lon0) * rad, p = lat * rad, p0 = LOC.lat0 * rad;
  const x = Math.cos(p) * Math.sin(l);
  const y = Math.cos(p0) * Math.sin(p) - Math.sin(p0) * Math.cos(p) * Math.cos(l);
  return [LOC.w / 2 + LOC.r * x, LOC.h / 2 - LOC.r * y];
}

// Douglas–Peucker in screen pixels (open polyline: the closing point is dropped first).
function simplify(pts, tol) {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1;
    let max = 0, idx = -1;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len;
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol && idx > 0) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const area = (pts) => Math.abs(pts.reduce((s, [x, y], i) => {
  const [nx, ny] = pts[(i + 1) % pts.length];
  return s + x * ny - nx * y;
}, 0) / 2);

const toPath = (rings) =>
  rings.map((r) => "M" + r.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join("L") + "Z").join("");

function rings(geometry, proj, { tol, minArea, inFrame }) {
  const polys = geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
  const out = [];
  for (const poly of polys) {
    const pts = poly[0].slice(0, -1).map(proj);
    if (inFrame && !pts.some(inFrame)) continue;
    if (area(pts) < minArea) continue;
    const s = simplify(pts, tol);
    if (s.length >= 3) out.push(s);
  }
  return out;
}

const src = process.argv[2];
if (!src) throw new Error("Pass the path to ne_50m_admin_0_countries.geojson");
const geo = JSON.parse(readFileSync(src, "utf8"));

const PAD = 40;
const inFrame = ([x, y]) => x > -PAD && x < W + PAD && y > -PAD && y < H + PAD;

const countries = [];
const locator = [];
for (const f of geo.features) {
  const { ADM0_A3: id, NAME: name, CONTINENT } = f.properties;
  const r = rings(f.geometry, project, { tol: 0.25, minArea: 1, inFrame });
  if (r.length) countries.push({ id, name, d: toPath(r) });
  if (CONTINENT === "Africa") {
    const l = rings(f.geometry, projectLoc, { tol: 0.35, minArea: 0.6 });
    if (l.length) locator.push({ id, d: toPath(l) });
  }
}
countries.sort((a, b) => a.id.localeCompare(b.id));
locator.sort((a, b) => a.id.localeCompare(b.id));

// The main frame drawn as a box on the locator.
const edge = [];
for (let i = 0; i <= 10; i++) edge.push([LON_W + ((LON_E - LON_W) * i) / 10, LAT_N]);
for (let i = 0; i <= 10; i++) edge.push([LON_E, LAT_N - ((LAT_N - LAT_S) * i) / 10]);
for (let i = 0; i <= 10; i++) edge.push([LON_E - ((LON_E - LON_W) * i) / 10, LAT_S]);
for (let i = 0; i <= 10; i++) edge.push([LON_W, LAT_S + ((LAT_N - LAT_S) * i) / 10]);
const frame = toPath([edge.map(projectLoc)]);

const ts = `// Generated by scripts/build-africa-map.mjs from Natural Earth 1:50m admin-0 countries
// (public domain). Do not edit by hand; re-run the script instead.

/**
 * The homepage map frame: equirectangular, standard parallel 14°N, 1920×860 px, matching
 * public/images/regmap-satellite.jpg pixel for pixel.
 */
export const VIEW = ${JSON.stringify(VIEW)} as const;

/** [lon, lat] → [x, y] in the map frame. */
export function project(lon: number, lat: number): [number, number] {
  return [(lon - VIEW.lonW) * VIEW.kx, (VIEW.latN - lat) * VIEW.k];
}

export type MapCountry = {
  /** ADM0_A3 code from Natural Earth. */
  id: string;
  name: string;
  /** SVG path in map-frame pixels. */
  d: string;
};

/** Every country that reaches into the frame. */
export const COUNTRIES: MapCountry[] = ${JSON.stringify(countries).replace(/\},\{/g, "},\n  {")};

/** Locator inset: Africa on a small orthographic globe (${LOC.w}×${LOC.h}), and the main frame's outline on it. */
export const LOCATOR = {
  w: ${LOC.w},
  h: ${LOC.h},
  countries: ${JSON.stringify(locator).replace(/\},\{/g, "},\n    {")} as { id: string; d: string }[],
  frame: ${JSON.stringify(frame)},
};
`;

const dest = fileURLToPath(new URL("../src/data/westAfricaMap.ts", import.meta.url));
writeFileSync(dest, ts);
console.log(`${countries.length} countries, ${(ts.length / 1024).toFixed(0)} KB → ${dest}`);

// Imagery: 2× the frame so terrain stays crisp on high-density screens.
const url =
  "https://gibs.earthdata.nasa.gov/wms/epsg4326/best/wms.cgi?SERVICE=WMS&REQUEST=GetMap&VERSION=1.3.0" +
  "&LAYERS=BlueMarble_ShadedRelief_Bathymetry&STYLES=&CRS=EPSG:4326&FORMAT=image/jpeg" +
  `&BBOX=${LAT_S},${LON_W},${LAT_N},${LON_E}&WIDTH=${W * 2}&HEIGHT=${H * 2}`;
const res = await fetch(url);
const type = res.headers.get("content-type") ?? "";
if (!res.ok || !type.startsWith("image/")) throw new Error(`Imagery request failed: ${res.status} ${type}`);
const img = fileURLToPath(new URL("../public/images/regmap-satellite.jpg", import.meta.url));
writeFileSync(img, Buffer.from(await res.arrayBuffer()));
console.log(`imagery → ${img}`);
